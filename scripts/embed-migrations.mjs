// Turns ./drizzle/*.sql into a TypeScript module so migrations ship inside the
// server bundle (no runtime file reads → works on Vercel, Docker and locally).
// Run after `drizzle-kit generate`:  npm run db:embed
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..");
const dir = path.join(root, "drizzle");
const journal = JSON.parse(fs.readFileSync(path.join(dir, "meta", "_journal.json"), "utf8"));
const migrations = journal.entries.map((e) => {
  const sql = fs.readFileSync(path.join(dir, `${e.tag}.sql`), "utf8");
  const statements = sql.split("--> statement-breakpoint").map((s) => s.trim()).filter(Boolean);
  return { tag: e.tag, statements };
});
const out = `// AUTO-GENERATED by scripts/embed-migrations.mjs — do not edit by hand.\nexport const MIGRATIONS: { tag: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};\n`;
fs.writeFileSync(path.join(root, "src", "server", "db", "migrations.generated.ts"), out);
console.log(`Embedded ${migrations.length} migrations.`);
